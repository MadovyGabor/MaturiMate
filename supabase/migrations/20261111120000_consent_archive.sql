-- Proof of consent that survives the deletion of an account (decision 2026-11-11, content/DECISIONS.md).
--
-- Deleting an account removes every row of the user, the consents included (ON DELETE CASCADE). The operator has to be
-- able to show later that a person accepted a document (GDPR art. 7(1); art. 17(3)(e) allows keeping what is needed
-- for legal claims). So the account deletion (Milestone 12.6) first copies the consents here, then deletes the user.
--
-- The table holds the minimum and nothing else: no progress, no name, no readable e-mail address. The e-mail is kept as
-- an HMAC with a secret that only the server knows: it cannot be read back, but a person who claims "I never agreed"
-- can be found by computing the HMAC of the address they give. `user_id` has no foreign key, because the user is gone.
-- Rows are removed when `delete_after` has passed (the period is confirmed in the legal review, 16.1).
--
-- Only the server writes and reads it (the 12.6 deletion function, SECURITY DEFINER, and the operator). The app has no
-- access: row level security is on, there is no policy, and the grants are removed.

CREATE TABLE consent_archive (
    archive_id          bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id             uuid         NOT NULL,
    email_hmac          text         NOT NULL,
    consent_type        varchar(30)  NOT NULL,
    document_version    varchar(20)  NOT NULL,
    accepted_at         timestamptz  NOT NULL,
    withdrawn_at        timestamptz,
    account_deleted_at  timestamptz  NOT NULL DEFAULT now(),
    delete_after        timestamptz  NOT NULL DEFAULT now() + interval '3 years',
    CONSTRAINT pk_consent_archive PRIMARY KEY (archive_id),
    CONSTRAINT ck_consent_archive_type
        CHECK (consent_type IN ('TERMS', 'PRIVACY', 'MARKETING', 'PARENTAL', 'AGE_16')),
    CONSTRAINT ck_consent_archive_withdrawn
        CHECK (withdrawn_at IS NULL OR withdrawn_at >= accepted_at),
    CONSTRAINT ck_consent_archive_retention
        CHECK (delete_after > account_deleted_at)
);

-- the lookup of a claim ("this e-mail address never agreed") and the clean-up of expired rows
CREATE INDEX idx_consent_archive_email_hmac ON consent_archive (email_hmac);
CREATE INDEX idx_consent_archive_delete_after ON consent_archive (delete_after);

ALTER TABLE consent_archive ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON consent_archive FROM anon, authenticated;

-- ---------------------------------------------------------------------
-- The deletion of an account, on the server
-- ---------------------------------------------------------------------
-- The app calls only this function. It runs with the rights of its owner (SECURITY DEFINER), so a user cannot delete
-- an account without the archive step (a delete through the API is not possible: auth.users is not reachable). In one
-- transaction it copies the consents to consent_archive (e-mail as HMAC, key from the Vault secret `consent_hmac_key`),
-- then deletes the Auth user; every row of the user goes with it (ON DELETE CASCADE). If the key is missing, nothing is
-- deleted. A user can delete only their own account (auth.uid()).

CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;

CREATE FUNCTION public.delete_my_account() RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    uid     uuid := (SELECT auth.uid());
    mail    text;
    secret  text;
BEGIN
    IF uid IS NULL THEN
        RAISE EXCEPTION 'not signed in' USING ERRCODE = 'insufficient_privilege';
    END IF;

    SELECT lower(btrim(u.email)) INTO mail FROM auth.users u WHERE u.id = uid;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'no such account';
    END IF;

    SELECT s.decrypted_secret INTO secret FROM vault.decrypted_secrets s WHERE s.name = 'consent_hmac_key';
    IF secret IS NULL OR secret = '' THEN
        RAISE EXCEPTION 'consent_hmac_key is not set: the account is not deleted';
    END IF;

    INSERT INTO public.consent_archive
        (user_id, email_hmac, consent_type, document_version, accepted_at, withdrawn_at)
    SELECT c.user_id,
           encode(extensions.hmac(coalesce(nullif(mail, ''), uid::text), secret, 'sha256'), 'hex'),
           c.consent_type, c.document_version, c.accepted_at, c.withdrawn_at
    FROM public.user_consent c
    WHERE c.user_id = uid;

    DELETE FROM auth.users WHERE id = uid;
END;
$$;

REVOKE ALL ON FUNCTION public.delete_my_account FROM PUBLIC;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON FUNCTION public.delete_my_account FROM anon;
    END IF;
END;
$$;
GRANT EXECUTE ON FUNCTION public.delete_my_account TO authenticated;
