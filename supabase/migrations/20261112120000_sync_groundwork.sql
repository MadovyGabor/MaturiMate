-- Groundwork for the sync and the content download (roadmap 12.1b, plan llm/outputs/plan-12.md section 2.2).
-- Phone side: database/src/commonMain/sqldelight/user/migrations/6.sqm.
--
-- * user_subject: a dropped subject is marked (removed_at), not deleted, so the removal can travel; updated_at.
-- * server_updated_at on every synced table: the cursor of the pull. The server sets it on every insert and update;
--   the phone never sees it.
-- * fn_set_updated_at keeps the phone's change time when the sync writes (session flag maturimate.sync), so the
--   merge is "last change wins", not "last upload wins". Direct writes through the API stay stamped by the server.
-- * exam_date (official dates), content_release (the packs offered) and content_download (the daily-limit log).

-- ---------------------------------------------------------------------
-- user_subject
-- ---------------------------------------------------------------------
ALTER TABLE user_subject ADD COLUMN removed_at timestamptz;
ALTER TABLE user_subject ADD COLUMN updated_at timestamptz NOT NULL DEFAULT now();

-- ---------------------------------------------------------------------
-- The clock rule
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_set_updated_at() RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
    IF current_setting('maturimate.sync', true) = 'on' AND NEW.updated_at IS DISTINCT FROM OLD.updated_at THEN
        RETURN NEW;
    END IF;
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_user_subject_updated_at
    BEFORE UPDATE ON user_subject FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- ---------------------------------------------------------------------
-- exam_date: the official dates of the written exams (the owner inserts a row when they are published)
-- ---------------------------------------------------------------------
CREATE TABLE exam_date (
    exam_date_id  smallint GENERATED BY DEFAULT AS IDENTITY,
    exam_year     smallint     NOT NULL,
    -- empty = every subject; a row for one subject overrides the general one
    subject_id    smallint,
    exam_on       date         NOT NULL,
    published_at  timestamptz  NOT NULL DEFAULT now(),
    note          varchar(200),
    CONSTRAINT pk_exam_date PRIMARY KEY (exam_date_id),
    CONSTRAINT fk_exam_date_subject FOREIGN KEY (subject_id) REFERENCES subject (subject_id) ON DELETE RESTRICT,
    CONSTRAINT ck_exam_date_year CHECK (exam_year BETWEEN 2026 AND 2100),
    CONSTRAINT ck_exam_date_match CHECK (extract(year FROM exam_on) = exam_year)
);
CREATE UNIQUE INDEX uq_exam_date_year_subject ON exam_date (exam_year, coalesce(subject_id, 0));

ALTER TABLE exam_date ENABLE ROW LEVEL SECURITY;
CREATE POLICY exam_date_select_all ON exam_date FOR SELECT TO authenticated USING (true);

-- ---------------------------------------------------------------------
-- content_release: the packs the app may download (written by the publish command of the pipeline)
-- ---------------------------------------------------------------------
CREATE TABLE content_release (
    release_id       smallint GENERATED BY DEFAULT AS IDENTITY,
    subject_id       smallint     NOT NULL,
    schema_version   smallint     NOT NULL,
    content_version  bigint       NOT NULL,
    -- the key of the pack in the private R2 bucket
    object_path      varchar(200) NOT NULL,
    size_bytes       bigint       NOT NULL,
    sha256           char(64)     NOT NULL,
    published_at     timestamptz  NOT NULL DEFAULT now(),
    is_current       boolean      NOT NULL DEFAULT true,
    CONSTRAINT pk_content_release PRIMARY KEY (release_id),
    CONSTRAINT fk_content_release_subject FOREIGN KEY (subject_id) REFERENCES subject (subject_id),
    CONSTRAINT uq_content_release UNIQUE (subject_id, schema_version, content_version),
    CONSTRAINT ck_content_release_size CHECK (size_bytes > 0)
);
CREATE UNIQUE INDEX uq_content_release_current ON content_release (subject_id, schema_version) WHERE is_current;

ALTER TABLE content_release ENABLE ROW LEVEL SECURITY;
CREATE POLICY content_release_select_current ON content_release FOR SELECT TO authenticated USING (is_current);

-- ---------------------------------------------------------------------
-- content_download: who asked for which pack (the daily limit, the count of versions). No IP address, device or place.
-- Only the SECURITY DEFINER function of step 12.4c reads and writes it.
-- ---------------------------------------------------------------------
CREATE TABLE content_download (
    download_id      bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id          uuid         NOT NULL,
    subject_id       smallint     NOT NULL,
    content_version  bigint       NOT NULL,
    requested_at     timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_content_download PRIMARY KEY (download_id),
    CONSTRAINT fk_content_download_user FOREIGN KEY (user_id) REFERENCES auth.users (id) ON DELETE CASCADE
);
CREATE INDEX ix_content_download_user ON content_download (user_id, subject_id, requested_at);

ALTER TABLE content_download ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON content_download FROM anon, authenticated;

-- ---------------------------------------------------------------------
-- server_updated_at: the pull cursor of the sync
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_set_server_updated_at() RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
    NEW.server_updated_at := clock_timestamp();
    RETURN NEW;
END;
$$;

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'user_profile', 'user_settings', 'user_subject', 'user_role', 'attempt', 'attempt_answer',
        'user_unit_progress', 'user_streak', 'activity_log', 'exam_date']
    LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN server_updated_at timestamptz NOT NULL DEFAULT clock_timestamp()', t);
        EXECUTE format(
            'CREATE TRIGGER %I BEFORE INSERT OR UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION fn_set_server_updated_at()',
            'trg_' || t || '_server_updated_at', t);
        IF t <> 'exam_date' THEN
            EXECUTE format('CREATE INDEX %I ON %I (user_id, server_updated_at)', 'ix_' || t || '_sync', t);
        END IF;
    END LOOP;
END;
$$;

-- ---------------------------------------------------------------------
-- save_sign_up: a subject dropped in the form is marked, not deleted (same shape as the phone)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.save_sign_up(
    p_first_name              text,
    p_last_name               text,
    p_teaching_language       text,
    p_graduation_date         date,
    p_ui_language             text,
    p_timezone                text,
    p_daily_goal_minutes      smallint,
    p_reminder_enabled        boolean,
    p_reminder_time           time,
    p_role_id                 smallint,
    p_subjects                jsonb,
    p_consents                text[],
    p_document_version        text,
    p_onboarding_completed_at timestamptz
) RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
    uid uuid := (SELECT auth.uid());
BEGIN
    IF uid IS NULL THEN
        RAISE EXCEPTION 'not signed in' USING ERRCODE = 'insufficient_privilege';
    END IF;

    INSERT INTO public.user_profile (user_id, first_name, last_name, teaching_language, graduation_date, onboarding_completed_at)
    VALUES (uid, p_first_name, p_last_name, p_teaching_language, p_graduation_date, p_onboarding_completed_at)
    ON CONFLICT (user_id) DO UPDATE SET
        first_name = EXCLUDED.first_name,
        last_name = EXCLUDED.last_name,
        teaching_language = EXCLUDED.teaching_language,
        graduation_date = EXCLUDED.graduation_date,
        onboarding_completed_at = EXCLUDED.onboarding_completed_at;

    INSERT INTO public.user_settings (user_id, ui_language, timezone, daily_goal_minutes, reminder_enabled, reminder_time)
    VALUES (uid, p_ui_language, p_timezone, p_daily_goal_minutes, p_reminder_enabled, p_reminder_time)
    ON CONFLICT (user_id) DO UPDATE SET
        ui_language = EXCLUDED.ui_language,
        timezone = EXCLUDED.timezone,
        daily_goal_minutes = EXCLUDED.daily_goal_minutes,
        reminder_enabled = EXCLUDED.reminder_enabled,
        reminder_time = EXCLUDED.reminder_time;

    DELETE FROM public.user_role WHERE user_id = uid AND role_id IN (1, 2, 3);
    IF p_role_id IS NOT NULL THEN
        INSERT INTO public.user_role (user_id, role_id) VALUES (uid, p_role_id);
    END IF;

    -- the subjects not in the list are marked removed, the sent ones are inserted or brought back
    UPDATE public.user_subject SET removed_at = now()
    WHERE user_id = uid AND removed_at IS NULL
      AND subject_id NOT IN (SELECT s.subject_id
                             FROM jsonb_to_recordset(coalesce(p_subjects, '[]'::jsonb)) AS s(subject_id smallint));

    INSERT INTO public.user_subject (user_id, subject_id, source, level)
    SELECT uid, s.subject_id, s.source, s.level
    FROM jsonb_to_recordset(coalesce(p_subjects, '[]'::jsonb)) AS s(subject_id smallint, source varchar(10), level varchar(2))
    ON CONFLICT (user_id, subject_id) DO UPDATE SET
        removed_at = NULL, source = EXCLUDED.source, level = EXCLUDED.level;

    INSERT INTO public.user_consent (user_id, consent_type, document_version)
    SELECT uid, c, p_document_version FROM unnest(coalesce(p_consents, '{}'::text[])) AS c
    ON CONFLICT DO NOTHING;
END;
$$;
