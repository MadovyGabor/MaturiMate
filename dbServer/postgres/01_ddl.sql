-- ---- task formats: options and keys must fit the format -------------
CREATE FUNCTION fn_task_option_check() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_mode varchar(10);
    v_code varchar(30);
BEGIN
    SELECT f.answer_mode, f.code INTO v_mode, v_code
      FROM task t JOIN task_format f ON f.task_format_id = t.task_format_id
     WHERE t.task_id = NEW.task_id;
    IF v_mode <> 'CHOICE' THEN
        RAISE EXCEPTION 'task % has format % (typed answer) and cannot have options',
            NEW.task_id, v_code;
    END IF;
    IF NEW.option_role = 'PROMPT' AND v_code <> 'MATCHING' THEN
        RAISE EXCEPTION 'only MATCHING tasks can have PROMPT options (task %)', NEW.task_id;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_task_option_check
    BEFORE INSERT OR UPDATE ON task_option
    FOR EACH ROW EXECUTE FUNCTION fn_task_option_check();

CREATE FUNCTION fn_task_key_check() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_mode varchar(10);
    v_code varchar(30);
    v_role varchar(10);
BEGIN
    SELECT f.answer_mode, f.code INTO v_mode, v_code
      FROM task t JOIN task_format f ON f.task_format_id = t.task_format_id
     WHERE t.task_id = NEW.task_id;
    IF v_mode <> 'CHOICE' THEN
        RAISE EXCEPTION 'task % has a typed answer and cannot have a key row', NEW.task_id;
    END IF;

    SELECT option_role INTO v_role FROM task_option WHERE option_id = NEW.option_id;
    IF v_role <> 'ANSWER' THEN
        RAISE EXCEPTION 'the correct option of task % must have the role ANSWER', NEW.task_id;
    END IF;

    IF v_code = 'MATCHING' THEN
        IF NEW.prompt_option_id IS NULL THEN
            RAISE EXCEPTION 'a MATCHING key row needs a prompt option (task %)', NEW.task_id;
        END IF;
        SELECT option_role INTO v_role FROM task_option WHERE option_id = NEW.prompt_option_id;
        IF v_role <> 'PROMPT' THEN
            RAISE EXCEPTION 'the prompt option of task % must have the role PROMPT', NEW.task_id;
        END IF;
    ELSIF NEW.prompt_option_id IS NOT NULL THEN
        RAISE EXCEPTION 'only MATCHING keys can have a prompt option (task %)', NEW.task_id;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_task_key_check
    BEFORE INSERT OR UPDATE ON task_key
    FOR EACH ROW EXECUTE FUNCTION fn_task_key_check();

CREATE FUNCTION fn_accepted_answer_check() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_mode varchar(10);
BEGIN
    SELECT f.answer_mode INTO v_mode
      FROM task t JOIN task_format f ON f.task_format_id = t.task_format_id
     WHERE t.task_id = NEW.task_id;
    IF v_mode <> 'TEXT' THEN
        RAISE EXCEPTION 'task % has a chosen answer and cannot have accepted text answers',
            NEW.task_id;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_task_accepted_answer_check
    BEFORE INSERT OR UPDATE ON task_accepted_answer
    FOR EACH ROW EXECUTE FUNCTION fn_accepted_answer_check();


