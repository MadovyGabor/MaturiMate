-- ---- topic tree: no cycles, content only on leaf topics -------------
CREATE FUNCTION fn_topic_check_tree() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_ancestor bigint;
BEGIN
    IF NEW.parent_topic_id IS NULL THEN
        RETURN NEW;
    END IF;

    -- a topic must not be moved below itself or one of its descendants
    IF TG_OP = 'UPDATE' THEN
        v_ancestor := NEW.parent_topic_id;
        WHILE v_ancestor IS NOT NULL LOOP
            IF v_ancestor = NEW.topic_id THEN
                RAISE EXCEPTION 'topic % cannot be placed below itself or its descendants',
                    NEW.topic_id;
            END IF;
            SELECT parent_topic_id INTO v_ancestor
              FROM topic WHERE topic_id = v_ancestor;
        END LOOP;
    END IF;

    -- a topic that holds tasks or learning units cannot get sub-topics
    IF EXISTS (SELECT 1 FROM task WHERE topic_id = NEW.parent_topic_id)
       OR EXISTS (SELECT 1 FROM learning_unit WHERE topic_id = NEW.parent_topic_id) THEN
        RAISE EXCEPTION 'topic % already holds tasks or learning units and cannot get sub-topics',
            NEW.parent_topic_id;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_topic_check_tree
    BEFORE INSERT OR UPDATE OF parent_topic_id ON topic
    FOR EACH ROW EXECUTE FUNCTION fn_topic_check_tree();

CREATE FUNCTION fn_require_leaf_topic() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM topic WHERE parent_topic_id = NEW.topic_id) THEN
        RAISE EXCEPTION 'topic % has sub-topics; tasks and learning units belong to leaf topics only',
            NEW.topic_id;
    END IF;
    RETURN NEW;
END;
$$;

