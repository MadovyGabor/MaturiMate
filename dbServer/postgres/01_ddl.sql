-- =====================================================================
-- 2. INDEXES
-- (primary keys and UNIQUE constraints already have indexes;
--  these cover foreign keys and frequent queries)
-- =====================================================================

-- roots of the topic tree are unique per subject (NULL parents are not
-- compared by a plain UNIQUE constraint)
CREATE UNIQUE INDEX uq_topic_root_order ON topic (subject_id, order_index)
    WHERE parent_topic_id IS NULL;

-- only one season can be active
CREATE UNIQUE INDEX uq_season_single_active ON season (is_active) WHERE is_active;

CREATE INDEX ix_user_role_role            ON user_role (role_id);
CREATE INDEX ix_user_session_user         ON user_session (user_id);
CREATE INDEX ix_password_reset_token_user ON password_reset_token (user_id);
CREATE INDEX ix_user_consent_user         ON user_consent (user_id);
CREATE INDEX ix_user_subject_subject      ON user_subject (subject_id);
CREATE INDEX ix_task_topic                ON task (topic_id);
