    display_name       varchar(50),
    date_of_birth      date         NOT NULL,
    school_type        varchar(20),
    teaching_language  varchar(2),
    graduation_date    date,
    CONSTRAINT pk_user_profile PRIMARY KEY (user_id),
    CONSTRAINT fk_user_profile_user FOREIGN KEY (user_id)
        REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT ck_user_profile_birth CHECK (date_of_birth >= DATE '1900-01-01'),
    CONSTRAINT ck_user_profile_school_type
        CHECK (school_type IN ('GYMNASIUM', 'VOCATIONAL', 'OTHER')),
    CONSTRAINT ck_user_profile_language CHECK (teaching_language IN ('SK', 'HU'))
);

CREATE TABLE user_settings (
    user_id             bigint      NOT NULL,
    ui_language         varchar(2)  NOT NULL DEFAULT 'SK',
    timezone            varchar(50) NOT NULL DEFAULT 'Europe/Bratislava',
    theme               varchar(10) NOT NULL DEFAULT 'SYSTEM',
    daily_goal_minutes  smallint    DEFAULT 10,
    reminder_enabled    boolean     NOT NULL DEFAULT false,
    reminder_time       time,
    CONSTRAINT pk_user_settings PRIMARY KEY (user_id),
    CONSTRAINT fk_user_settings_user FOREIGN KEY (user_id)
        REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT ck_user_settings_language CHECK (ui_language IN ('SK', 'HU')),
    CONSTRAINT ck_user_settings_theme CHECK (theme IN ('LIGHT', 'DARK', 'SYSTEM')),
    CONSTRAINT ck_user_settings_goal
        CHECK (daily_goal_minutes BETWEEN 1 AND 240),
    CONSTRAINT ck_user_settings_reminder
        CHECK (NOT reminder_enabled OR reminder_time IS NOT NULL)
);

CREATE TABLE user_subject (
    user_id       bigint      NOT NULL,
    subject_id    smallint    NOT NULL,
    target_score  decimal(5,2),
    source        varchar(10) NOT NULL DEFAULT 'CHOSEN',
    added_at      timestamp   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_user_subject PRIMARY KEY (user_id, subject_id),
    CONSTRAINT fk_user_subject_user FOREIGN KEY (user_id)
        REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_user_subject_subject FOREIGN KEY (subject_id)
        REFERENCES subject (subject_id) ON DELETE RESTRICT,
    CONSTRAINT ck_user_subject_score CHECK (target_score BETWEEN 0 AND 100),
    CONSTRAINT ck_user_subject_source CHECK (source IN ('AUTO', 'CHOSEN'))
);

-- ---------------------------------------------------------------------
-- Domain 3 - Curriculum and task bank
-- ---------------------------------------------------------------------

CREATE TABLE topic (
    topic_id         bigint GENERATED BY DEFAULT AS IDENTITY,
    subject_id       smallint,
    parent_topic_id  bigint,
    title            varchar(150) NOT NULL,
    description      varchar(500),
    order_index      smallint     NOT NULL,
    is_published     boolean      NOT NULL DEFAULT false,
    CONSTRAINT pk_topic PRIMARY KEY (topic_id),
    CONSTRAINT fk_topic_subject FOREIGN KEY (subject_id)
        REFERENCES subject (subject_id) ON DELETE RESTRICT,
    CONSTRAINT fk_topic_parent FOREIGN KEY (parent_topic_id)
        REFERENCES topic (topic_id) ON DELETE RESTRICT,
    CONSTRAINT uq_topic_parent_order UNIQUE (parent_topic_id, order_index),
    -- only root topics (no parent) carry the subject
    CONSTRAINT ck_topic_root_subject
        CHECK ((parent_topic_id IS NULL) = (subject_id IS NOT NULL)),
    CONSTRAINT ck_topic_not_own_parent CHECK (parent_topic_id <> topic_id)
);

CREATE TABLE task_format (
    task_format_id  smallint GENERATED BY DEFAULT AS IDENTITY,
    code            varchar(30)  NOT NULL,
    name            varchar(100) NOT NULL,
    answer_mode     varchar(10)  NOT NULL,
    description     varchar(255),
    CONSTRAINT pk_task_format PRIMARY KEY (task_format_id),
    CONSTRAINT uq_task_format_code UNIQUE (code),
    CONSTRAINT ck_task_format_mode CHECK (answer_mode IN ('CHOICE', 'TEXT'))
);

CREATE TABLE task (
    task_id            bigint GENERATED BY DEFAULT AS IDENTITY,
    topic_id           bigint    NOT NULL,
    task_format_id     smallint  NOT NULL,
    question_text      text      NOT NULL,
    explanation        text,
    max_points         smallint  NOT NULL DEFAULT 1,
    answer_word_limit  smallint,
    is_active          boolean   NOT NULL DEFAULT true,
    created_at         timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_task PRIMARY KEY (task_id),
    CONSTRAINT fk_task_topic FOREIGN KEY (topic_id)
        REFERENCES topic (topic_id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_format FOREIGN KEY (task_format_id)
        REFERENCES task_format (task_format_id) ON DELETE RESTRICT,
    CONSTRAINT ck_task_points CHECK (max_points >= 1),
    CONSTRAINT ck_task_word_limit CHECK (answer_word_limit > 0)
);

CREATE TABLE task_option (
    option_id     bigint GENERATED BY DEFAULT AS IDENTITY,
    task_id       bigint       NOT NULL,
    option_role   varchar(10)  NOT NULL DEFAULT 'ANSWER',
    option_label  varchar(5)   NOT NULL,
    option_text   varchar(500) NOT NULL,
    CONSTRAINT pk_task_option PRIMARY KEY (option_id),
    CONSTRAINT fk_task_option_task FOREIGN KEY (task_id)
        REFERENCES task (task_id) ON DELETE CASCADE,
    -- lets task_key use composite foreign keys (option belongs to the same task)
    CONSTRAINT uq_task_option_task_option UNIQUE (task_id, option_id),
    CONSTRAINT uq_task_option_label UNIQUE (task_id, option_role, option_label),
    CONSTRAINT ck_task_option_role CHECK (option_role IN ('ANSWER', 'PROMPT'))
);

CREATE TABLE task_key (
    task_id           bigint   NOT NULL,
    answer_slot       smallint NOT NULL DEFAULT 1,
    prompt_option_id  bigint,
    option_id         bigint   NOT NULL,
    CONSTRAINT pk_task_key PRIMARY KEY (task_id, answer_slot),
    CONSTRAINT fk_task_key_task FOREIGN KEY (task_id)
        REFERENCES task (task_id) ON DELETE CASCADE,
    CONSTRAINT fk_task_key_option FOREIGN KEY (task_id, option_id)
        REFERENCES task_option (task_id, option_id) ON DELETE CASCADE,
    CONSTRAINT fk_task_key_prompt FOREIGN KEY (task_id, prompt_option_id)
        REFERENCES task_option (task_id, option_id) ON DELETE CASCADE,
    CONSTRAINT ck_task_key_slot CHECK (answer_slot >= 1)
);

CREATE TABLE task_accepted_answer (
    accepted_answer_id  bigint GENERATED BY DEFAULT AS IDENTITY,
    task_id             bigint       NOT NULL,
    answer_slot         smallint     NOT NULL DEFAULT 1,
    answer_text         varchar(300) NOT NULL,
    case_sensitive      boolean      NOT NULL DEFAULT false,
    CONSTRAINT pk_task_accepted_answer PRIMARY KEY (accepted_answer_id),
    CONSTRAINT fk_task_accepted_answer_task FOREIGN KEY (task_id)
        REFERENCES task (task_id) ON DELETE CASCADE,
    CONSTRAINT uq_task_accepted_answer UNIQUE (task_id, answer_slot, answer_text),
    CONSTRAINT ck_task_accepted_answer_slot CHECK (answer_slot >= 1)
);

CREATE TABLE task_attachment (
    attachment_id  bigint GENERATED BY DEFAULT AS IDENTITY,
    task_id        bigint       NOT NULL,
    file_url       varchar(500) NOT NULL,
    media_type     varchar(30)  NOT NULL,
    alt_text       varchar(300),
    CONSTRAINT pk_task_attachment PRIMARY KEY (attachment_id),
    CONSTRAINT fk_task_attachment_task FOREIGN KEY (task_id)
