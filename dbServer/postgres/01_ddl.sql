-- ---------------------------------------------------------------------
-- Domain 1 - Authentication and identity
-- ---------------------------------------------------------------------

CREATE TABLE role (
    role_id      smallint GENERATED BY DEFAULT AS IDENTITY,
    code         varchar(30)  NOT NULL,
    name         varchar(60)  NOT NULL,
    description  varchar(255),
    CONSTRAINT pk_role      PRIMARY KEY (role_id),
    CONSTRAINT uq_role_code UNIQUE (code)
);

CREATE TABLE app_user (
    user_id             bigint GENERATED BY DEFAULT AS IDENTITY,
    email               varchar(254) NOT NULL,
    password_hash       varchar(255) NOT NULL,
    email_verified_at   timestamp,
    is_active           boolean      NOT NULL DEFAULT true,
    failed_login_count  smallint     NOT NULL DEFAULT 0,
    locked_until        timestamp,
    last_login_at       timestamp,
    created_at          timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at          timestamp,
    CONSTRAINT pk_app_user      PRIMARY KEY (user_id),
    CONSTRAINT uq_app_user_email UNIQUE (email),
    CONSTRAINT ck_app_user_email
        CHECK (email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT ck_app_user_failed_login CHECK (failed_login_count >= 0)
);

CREATE TABLE user_role (
    user_id      bigint    NOT NULL,
    role_id      smallint  NOT NULL,
    assigned_at  timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_user_role PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_role_user FOREIGN KEY (user_id)
        REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_user_role_role FOREIGN KEY (role_id)
        REFERENCES role (role_id) ON DELETE RESTRICT
);

CREATE TABLE user_session (
    session_id          bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id             bigint       NOT NULL,
    refresh_token_hash  varchar(255) NOT NULL,
    platform            varchar(20)  NOT NULL,
    device_id           varchar(100),
    ip_address          varchar(45),
    created_at          timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at          timestamp    NOT NULL,
    revoked_at          timestamp,
    CONSTRAINT pk_user_session PRIMARY KEY (session_id),
    CONSTRAINT uq_user_session_token UNIQUE (refresh_token_hash),
    CONSTRAINT fk_user_session_user FOREIGN KEY (user_id)
        REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT ck_user_session_platform
        CHECK (platform IN ('ANDROID', 'DESKTOP_JVM', 'WEB_APP')),
    CONSTRAINT ck_user_session_expiry CHECK (expires_at > created_at)
);

CREATE TABLE password_reset_token (
    token_id    bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id     bigint       NOT NULL,
    token_hash  varchar(255) NOT NULL,
    created_at  timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at  timestamp    NOT NULL,
    used_at     timestamp,
    CONSTRAINT pk_password_reset_token PRIMARY KEY (token_id),
    CONSTRAINT uq_password_reset_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_password_reset_token_user FOREIGN KEY (user_id)
        REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT ck_password_reset_token_expiry CHECK (expires_at > created_at)
);

CREATE TABLE user_consent (
    consent_id        bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id           bigint      NOT NULL,
    consent_type      varchar(30) NOT NULL,
    document_version  varchar(20) NOT NULL,
    accepted_at       timestamp   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    withdrawn_at      timestamp,
    CONSTRAINT pk_user_consent PRIMARY KEY (consent_id),
    CONSTRAINT fk_user_consent_user FOREIGN KEY (user_id)
        REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT ck_user_consent_type
        CHECK (consent_type IN ('TERMS', 'PRIVACY', 'MARKETING', 'PARENTAL')),
    CONSTRAINT ck_user_consent_withdrawn
        CHECK (withdrawn_at IS NULL OR withdrawn_at >= accepted_at)
);

