CREATE TRIGGER trg_learning_unit_leaf_topic
    BEFORE INSERT OR UPDATE OF topic_id ON learning_unit
    FOR EACH ROW EXECUTE FUNCTION fn_require_leaf_topic();

-- ---- only practice units hold tasks ---------------------------------
